BEGIN
 EXECUTE IMMEDIATE 'CREATE TABLE RISK_PREDICTION_HISTORY (HISTORY_ID NUMBER PRIMARY KEY,PREDICTION_ID NUMBER,STUDENT_ID NUMBER NOT NULL,RISK_LEVEL VARCHAR2(20),RISK_PROBABILITY NUMBER(5,2),PREDICTION_DATE DATE,RECORDED_AT DATE DEFAULT SYSDATE,CHANGE_TYPE VARCHAR2(20))';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;
/
CREATE OR REPLACE TRIGGER TRG_RISK_PREDICTION_HISTORY
AFTER UPDATE OR DELETE ON RISK_PREDICTION FOR EACH ROW
DECLARE v_id NUMBER;
BEGIN
 SELECT NVL(MAX(HISTORY_ID),0)+1 INTO v_id FROM RISK_PREDICTION_HISTORY;
 INSERT INTO RISK_PREDICTION_HISTORY VALUES(v_id,:OLD.PREDICTION_ID,:OLD.STUDENT_ID,:OLD.RISK_LEVEL,:OLD.RISK_PROBABILITY,:OLD.PREDICTION_DATE,SYSDATE,CASE WHEN UPDATING THEN 'UPDATE' ELSE 'DELETE' END);
END;
/
CREATE OR REPLACE VIEW STUDENT_RISK_ANALYTICS AS
SELECT s.DEPARTMENT,s.SEMESTER,COUNT(*) STUDENT_COUNT,ROUND(AVG(a.ATTENDANCE_PERCENT),2) AVG_ATTENDANCE,
SUM(CASE WHEN r.RISK_LEVEL='HIGH' THEN 1 ELSE 0 END) HIGH_RISK,
SUM(CASE WHEN r.RISK_LEVEL='MEDIUM' THEN 1 ELSE 0 END) MEDIUM_RISK,
SUM(CASE WHEN r.RISK_LEVEL='LOW' THEN 1 ELSE 0 END) LOW_RISK
FROM STUDENT s JOIN ATTENDANCE a ON s.STUDENT_ID=a.STUDENT_ID JOIN RISK_PREDICTION r ON s.STUDENT_ID=r.STUDENT_ID
WHERE r.PREDICTION_ID=(SELECT MAX(r2.PREDICTION_ID) FROM RISK_PREDICTION r2 WHERE r2.STUDENT_ID=s.STUDENT_ID)
GROUP BY s.DEPARTMENT,s.SEMESTER;
