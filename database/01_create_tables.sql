-- ============================================
-- AI-BASED STUDENT ATTENDANCE RISK PREDICTION
-- Database Table Creation
-- ============================================

-- 1. STUDENT TABLE
CREATE TABLE STUDENT (
    STUDENT_ID NUMBER PRIMARY KEY,
    STUDENT_NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(100),
    DEPARTMENT VARCHAR2(50),
    SEMESTER NUMBER
);


-- 2. ATTENDANCE TABLE
CREATE TABLE ATTENDANCE (
    ATTENDANCE_ID NUMBER PRIMARY KEY,
    STUDENT_ID NUMBER NOT NULL,
    TOTAL_CLASSES NUMBER NOT NULL,
    CLASSES_ATTENDED NUMBER NOT NULL,
    ATTENDANCE_PERCENT NUMBER(5,2),

    CONSTRAINT FK_ATTENDANCE_STUDENT
        FOREIGN KEY (STUDENT_ID)
        REFERENCES STUDENT(STUDENT_ID)
);


-- 3. ACADEMIC PERFORMANCE TABLE
CREATE TABLE ACADEMIC_PERFORMANCE (
    PERFORMANCE_ID NUMBER PRIMARY KEY,
    STUDENT_ID NUMBER NOT NULL,
    INTERNAL_MARKS NUMBER(5,2),
    ASSIGNMENT_PERCENT NUMBER(5,2),
    PREVIOUS_RESULT VARCHAR2(20),

    CONSTRAINT FK_PERFORMANCE_STUDENT
        FOREIGN KEY (STUDENT_ID)
        REFERENCES STUDENT(STUDENT_ID)
);


-- 4. RISK PREDICTION TABLE
CREATE TABLE RISK_PREDICTION (
    PREDICTION_ID NUMBER PRIMARY KEY,
    STUDENT_ID NUMBER NOT NULL,
    RISK_LEVEL VARCHAR2(20),
    RISK_PROBABILITY NUMBER(5,2),
    PREDICTION_DATE DATE DEFAULT SYSDATE,

    CONSTRAINT FK_PREDICTION_STUDENT
        FOREIGN KEY (STUDENT_ID)
        REFERENCES STUDENT(STUDENT_ID)
);